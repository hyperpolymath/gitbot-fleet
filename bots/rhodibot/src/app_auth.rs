    #[tokio::test]
    async fn a_rejected_token_request_is_an_error_not_a_panic() {
        let server = MockServer::start().await;
        Mock::given(method("POST"))
            .and(path("/app/installations/5/access_tokens"))
            .respond_with(ResponseTemplate::new(401).set_body_string("Bad credentials"))
            .mount(&server)
            .await;

        let auth = auth_for(&server);
        let error = auth
            .installation_token(5)
            .await
            .expect_err("must fail")
            .to_string();
        assert!(error.contains("401"), "should name the status: {error}");
        assert!(
            !error.contains("ghs_"),
            "an error must never echo a credential: {error}"
        );
    }

