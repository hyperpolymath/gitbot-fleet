//! GitHub App authentication: RS256 app JWTs and installation tokens.
//!
//! # Why this module exists
//!
//! Until this landed, the only credential the bot understood was a
//! `GITHUB_TOKEN` environment variable — a single token, scoped to a single
//! repository, which is not how a GitHub App works. An App authenticates in two
//! steps:
//!
//! 1. Sign a short-lived JWT (RS256) with the App's private key, and present it
//!    as `iss` = the App ID. This is the *app* identity.
//! 2. Exchange that JWT for an *installation* token, which is what actually
//!    carries permissions on repositories the App is installed on. Those tokens
//!    expire after an hour, so they are cached and refreshed here.
//!
//! # Security considerations
//!
//! - The private key is parsed once at start-up into an opaque key pair and is
//!   never logged, serialised, or included in an error message.
//! - Signing uses `ring`, which is already in the dependency tree via rustls.
//!   No hand-rolled bignum arithmetic is involved.
//! - Installation tokens are held in memory with their expiry and are refreshed
//!   five minutes early, so a request never races the expiry.
//! - Errors carry a status code and a context string, never a credential.

use std::sync::Mutex;

use anyhow::{Context, Result, anyhow};
use base64::Engine;
use base64::engine::general_purpose::{STANDARD, URL_SAFE_NO_PAD};
use chrono::{DateTime, Duration as ChronoDuration, Utc};
use ring::rand::SystemRandom;
use ring::signature::{RSA_PKCS1_SHA256, RsaKeyPair};
use serde::Deserialize;

/// User agent presented to the GitHub API.
pub const USER_AGENT: &str = "rhodibot";

/// Longest JWT lifetime GitHub accepts, minus a margin. GitHub rejects `exp`
/// more than ten minutes in the future.
const JWT_LIFETIME_SECS: i64 = 540;

/// Backdate `iat` to tolerate clock drift between us and GitHub.
const JWT_BACKDATE_SECS: i64 = 60;

/// Refresh an installation token this long before it expires.
const TOKEN_REFRESH_MARGIN_SECS: i64 = 300;

/// A cached installation token and the moment it stops being usable.
#[derive(Clone)]
struct CachedToken {
    installation_id: u64,
    token: String,
    expires_at: DateTime<Utc>,
}

#[derive(Deserialize)]
struct InstallationTokenResponse {
    token: String,
    expires_at: DateTime<Utc>,
}

#[derive(Deserialize)]
struct InstallationResponse {
    id: u64,
}

/// GitHub App authentication.
///
/// Holds the parsed private key and a cache of installation tokens. Cheap to
/// clone-sharing: wrap in an `Arc` and share the client between handlers.
pub struct AppAuth {
    app_id: u64,
    key_pair: RsaKeyPair,
    client: reqwest::Client,
    api_url: String,
    cached: Mutex<Option<CachedToken>>,
}

impl AppAuth {
    /// Build from an App ID and a PEM private key.
    ///
    /// Accepts both PEM forms GitHub hands out: PKCS#1 (`BEGIN RSA PRIVATE
    /// KEY`) and PKCS#8 (`BEGIN PRIVATE KEY`). Historically GitHub App keys are
    /// PKCS#1, while anything generated by recent tooling is usually PKCS#8;
    /// accepting both avoids a deployment failing on a key format detail.
    pub fn new(app_id: u64, private_key_pem: &str, api_url: &str) -> Result<Self> {
        let der = pkcs8_der_from_pem(private_key_pem)?;
        let key_pair = RsaKeyPair::from_pkcs8(&der)
            .map_err(|_| anyhow!("the private key is not a usable RSA key"))?;

        Ok(Self {
            app_id,
            key_pair,
            client: reqwest::Client::new(),
            api_url: api_url.trim_end_matches('/').to_string(),
            cached: Mutex::new(None),
        })
    }

    /// The App ID this instance authenticates as.
    pub fn app_id(&self) -> u64 {
        self.app_id
    }

    /// A freshly signed app JWT. Exposed for the `--dump-jwt` style diagnostic
    /// path and for tests; callers normally want [`Self::installation_token`].
    pub fn app_jwt(&self) -> Result<String> {
        sign_app_jwt(self.app_id, &self.key_pair, Utc::now())
    }

    /// Find the installation ID for a repository, using the app JWT.
    ///
    /// This is how a webhook delivery learns which installation to act as,
    /// since the payload's `installation.id` is not always present.
    pub async fn installation_for_repository(&self, owner: &str, repo: &str) -> Result<u64> {
        let jwt = self.app_jwt()?;
        let url = format!("{}/repos/{owner}/{repo}/installation", self.api_url);
        let response = self
            .client
            .get(&url)
            .bearer_auth(jwt)
            .header("Accept", "application/vnd.github+json")
            .header("User-Agent", USER_AGENT)
            .header("X-GitHub-Api-Version", "2022-11-28")
            .send()
            .await
            .context("looking up the installation for a repository")?;

        let status = response.status();
        if !status.is_success() {
            return Err(anyhow!("installation lookup failed with HTTP {status}"));
        }

        let installation: InstallationResponse = response
            .json()
            .await
            .context("parsing the installation lookup response")?;
        Ok(installation.id)
    }

    /// An installation token for the given installation, from cache when it is
    /// still comfortably valid.
    pub async fn installation_token(&self, installation_id: u64) -> Result<String> {
        if let Some(token) = self.cached_token(installation_id) {
            return Ok(token);
        }

        let jwt = self.app_jwt()?;
        let url = format!(
            "{}/app/installations/{installation_id}/access_tokens",
            self.api_url
        );
        let response = self
            .client
            .post(&url)
            .bearer_auth(jwt)
            .header("Accept", "application/vnd.github+json")
            .header("User-Agent", USER_AGENT)
            .header("X-GitHub-Api-Version", "2022-11-28")
            .send()
            .await
            .context("requesting an installation token")?;

        let status = response.status();
        if !status.is_success() {
            return Err(anyhow!(
                "installation token request failed with HTTP {status}"
            ));
        }

        let body: InstallationTokenResponse = response
            .json()
            .await
            .context("parsing the installation token response")?;

        if let Ok(mut cache) = self.cached.lock() {
            *cache = Some(CachedToken {
                installation_id,
                token: body.token.clone(),
                expires_at: body.expires_at,
            });
        }

        Ok(body.token)
    }

    fn cached_token(&self, installation_id: u64) -> Option<String> {
        let cache = self.cached.lock().ok()?;
        let entry = cache.as_ref()?;
        if entry.installation_id != installation_id {
            return None;
        }
        let remaining = entry.expires_at.signed_duration_since(Utc::now());
        if remaining <= ChronoDuration::seconds(TOKEN_REFRESH_MARGIN_SECS) {
            return None;
        }
        Some(entry.token.clone())
    }
}

/// Sign a GitHub App JWT: the RS256 half of App authentication.
///
/// `now` is a parameter rather than read from the clock so the lifetimes are
/// testable.
pub fn sign_app_jwt(app_id: u64, key_pair: &RsaKeyPair, now: DateTime<Utc>) -> Result<String> {
    let header = serde_json::json!({ "alg": "RS256", "typ": "JWT" });
    let claims = serde_json::json!({
        "iat": now.timestamp() - JWT_BACKDATE_SECS,
        "exp": now.timestamp() + JWT_LIFETIME_SECS,
        // GitHub accepts either the App ID or the client ID here; the App ID is
        // the one this struct is constructed with.
        "iss": app_id.to_string(),
    });

    let signing_input = format!(
        "{}.{}",
        URL_SAFE_NO_PAD.encode(serde_json::to_vec(&header)?),
        URL_SAFE_NO_PAD.encode(serde_json::to_vec(&claims)?)
    );

    let rng = SystemRandom::new();
    let mut signature = vec![0u8; key_pair.public().modulus_len()];
    key_pair
        .sign(
            &RSA_PKCS1_SHA256,
            &rng,
            signing_input.as_bytes(),
            &mut signature,
        )
        .map_err(|_| anyhow!("signing the app JWT failed"))?;

    Ok(format!(
        "{signing_input}.{}",
        URL_SAFE_NO_PAD.encode(signature)
    ))
}

/// Decode a PEM private key to PKCS#8 DER, converting PKCS#1 if needed.
pub fn pkcs8_der_from_pem(pem: &str) -> Result<Vec<u8>> {
    let (label, body) = split_pem(pem)?;
    let der = STANDARD
        .decode(body.as_bytes())
        .context("the private key PEM body is not valid base64")?;

    match label.as_str() {
        "PRIVATE KEY" => Ok(der),
        "RSA PRIVATE KEY" => Ok(pkcs1_to_pkcs8(&der)),
        other => Err(anyhow!("unsupported private key type: {other}")),
    }
}

/// Split a PEM into its label and its base64 body, ignoring surrounding prose.
fn split_pem(pem: &str) -> Result<(String, String)> {
    let mut label: Option<String> = None;
    let mut body = String::new();

    for line in pem.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with("-----END ") {
            break;
        }
        if let Some(rest) = trimmed.strip_prefix("-----BEGIN ") {
            label = Some(rest.trim_end_matches('-').trim().to_string());
            continue;
        }
        if label.is_some() && !trimmed.is_empty() {
            body.push_str(trimmed);
        }
    }

    let label = label.ok_or_else(|| anyhow!("the private key is not PEM (no BEGIN line)"))?;
    if body.is_empty() {
        return Err(anyhow!("the private key PEM has an empty body"));
    }
    Ok((label, body))
}

/// Wrap a PKCS#1 `RSAPrivateKey` in a PKCS#8 `PrivateKeyInfo` envelope.
///
/// `ring` only accepts PKCS#8, and GitHub historically issues PKCS#1, so the
/// envelope is built here rather than pulling in an ASN.1 crate. The output is
/// byte-identical to `openssl pkcs8 -topk8 -nocrypt` for the same key, which is
/// asserted by a test.
fn pkcs1_to_pkcs8(pkcs1: &[u8]) -> Vec<u8> {
    // AlgorithmIdentifier for rsaEncryption with an explicit NULL parameter.
    const RSA_ENCRYPTION: [u8; 15] = [
        0x30, 0x0d, 0x06, 0x09, 0x2a, 0x86, 0x48, 0x86, 0xf7, 0x0d, 0x01, 0x01, 0x01, 0x05, 0x00,
    ];

    // privateKey OCTET STRING wrapping the PKCS#1 structure
    let mut octet = Vec::with_capacity(pkcs1.len() + 6);
    octet.push(0x04);
    octet.extend_from_slice(&der_len(pkcs1.len()));
    octet.extend_from_slice(pkcs1);

    // SEQUENCE { version INTEGER 0, algorithm, privateKey }
    let mut body = Vec::with_capacity(octet.len() + RSA_ENCRYPTION.len() + 3);
    body.extend_from_slice(&[0x02, 0x01, 0x00]);
    body.extend_from_slice(&RSA_ENCRYPTION);
    body.extend_from_slice(&octet);

    let mut out = Vec::with_capacity(body.len() + 6);
    out.push(0x30);
    out.extend_from_slice(&der_len(body.len()));
    out.extend_from_slice(&body);
    out
}

/// DER length encoding: short form below 128, otherwise long form.
fn der_len(len: usize) -> Vec<u8> {
    if len < 0x80 {
        return vec![len as u8];
    }
    let bytes = len.to_be_bytes();
    let first_significant = bytes
        .iter()
        .position(|byte| *byte != 0)
        .unwrap_or(bytes.len() - 1);

    let mut out = Vec::with_capacity(bytes.len() - first_significant + 1);
    out.push(0x80 | (bytes.len() - first_significant) as u8);
    out.extend_from_slice(&bytes[first_significant..]);
    out
}

