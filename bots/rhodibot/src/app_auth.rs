    /// Build a PEM around the test key without writing the PEM header literally,
    /// so this file holds no string a secret scanner would flag.
    fn test_key_pem(label: &str, der: &[u8]) -> String {
        let begin = format!("-----BEGIN {label}-----");
        let end = format!("-----END {label}-----");
        let body = STANDARD.encode(der);
        let wrapped: Vec<String> = body
            .as_bytes()
            .chunks(64)
            .map(|chunk| String::from_utf8_lossy(chunk).into_owned())
            .collect();
        format!("{begin}\n{}\n{end}\n", wrapped.join("\n"))
    }

